import { createHmac, timingSafeEqual } from "node:crypto";
import { deflateRawSync, inflateRawSync } from "node:zlib";

function encode(value) {
  return Buffer.from(value).toString("base64url");
}

function signature(body, secret) {
  return createHmac("sha256", secret).update(body).digest("base64url");
}

export function signSubtitleToken(payload, secret, now = Date.now()) {
  // Subtitle entries can contain several fallback providers and long release
  // names.  Encoding that JSON directly made some URLs exceed what Stremio's
  // local proxy accepts.  Raw DEFLATE keeps the token stateless while making
  // typical URLs several times shorter.  The leading "z" identifies the new
  // compressed format without adding another path separator.
  const json = JSON.stringify({ ...payload, exp: Math.floor(now / 1000) + 604800 });
  const body = `z${deflateRawSync(Buffer.from(json)).toString("base64url")}`;
  return `${body}.${signature(body, secret)}`;
}

export function verifySubtitleToken(token, secret, now = Date.now()) {
  const [body, supplied] = String(token).split(".");
  if (!body || !supplied) throw new Error("Invalid subtitle token");
  const expected = signature(body, secret);
  const a = Buffer.from(supplied);
  const b = Buffer.from(expected);
  if (a.length !== b.length || !timingSafeEqual(a, b)) throw new Error("Invalid subtitle token signature");
  // Keep accepting links generated by releases before 3.1.2 until they expire.
  // The signature is checked first, so only tokens this server created are
  // inflated; the output limit is defence in depth.
  const decoded = body.startsWith("z")
    ? inflateRawSync(Buffer.from(body.slice(1), "base64url"), { maxOutputLength: 256 * 1024 }).toString("utf8")
    : Buffer.from(body, "base64url").toString("utf8");
  const payload = JSON.parse(decoded);
  if (!payload || typeof payload !== "object") throw new Error("Invalid subtitle token payload");
  if (!payload.exp || payload.exp < Math.floor(now / 1000)) throw new Error("Subtitle token expired");
  return payload;
}
